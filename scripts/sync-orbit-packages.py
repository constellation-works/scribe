#!/usr/bin/env python3
"""Generate the Codex Orbit package from the canonical package; --check verifies parity."""
import argparse
import json
import pathlib
import stat
import sys


def replace_once(text, before, after):
    if text.count(before) != 1:
        raise ValueError(f"canonical manifest changed; update generator at {before!r}")
    return text.replace(before, after, 1)


def codex_manifest(raw):
    text = raw.decode()
    text = replace_once(text, "programs: [scribe, claude]", "programs: [scribe, claude, codex]")
    text = replace_once(
        text,
        'write: ["{{config.root}}", "{{plugin_state}}"]',
        'write: ["{{config.root}}", "{{plugin_state}}", "{{config.codex_runtime_tmp}}"]\n'
        '      write_files: ["{{config.codex_installation_id}}"]',
    )
    text = replace_once(
        text,
        '      # Optional Codex provider state: active/archive rollouts and existing auth.\n      codex_home: ""\n',
        '      # Codex paths are required workspace settings; see ../README.md.\n',
    )
    return ("# Generated by scripts/sync-orbit-packages.py; edit the canonical package/generator.\n" + text).encode()


def codex_schema(raw):
    schema = json.loads(raw)
    schema["description"] = "[plugins.scribe] settings for the Codex-enabled Orbit package."
    schema["properties"]["codex_home"]["description"] = (
        "Absolute existing Codex state directory, read-only for existing auth/config/transcripts. "
        "Required by this package; use the default Orbit package for Claude-only installations."
    )
    schema["properties"]["codex_runtime_tmp"] = {
        "type": "string",
        "description": "Absolute existing tmp directory inside codex_home; Codex needs this narrow directory write at startup.",
    }
    schema["properties"]["codex_installation_id"] = {
        "type": "string",
        "description": "Absolute existing installation_id regular file inside codex_home; exact-file write only, with no symlinks or hard links.",
    }
    for key in ("codex_home", "codex_runtime_tmp", "codex_installation_id"):
        schema["properties"][key].update(minLength=1, pattern="^/")
    schema["required"] = ["codex_home", "codex_runtime_tmp", "codex_installation_id"]
    return (json.dumps(schema, indent=2) + "\n").encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = pathlib.Path(__file__).resolve().parent.parent
    source = root / "plugin/.orbit-plugin"
    target = root / "plugin/orbit-codex/.orbit-plugin"
    expected = {}
    for path in sorted(source.rglob("*")):
        if not path.is_file():
            continue
        name = path.relative_to(source).as_posix()
        # The source-only Rust contract is compiled once; the variant has its own README.
        if name in ("README.md", "tests/conformance.rs"):
            continue
        raw = path.read_bytes()
        if name == "plugin.yaml":
            raw = codex_manifest(raw)
        elif name == "schemas/config.json":
            raw = codex_schema(raw)
        expected[name] = (raw, stat.S_IMODE(path.stat().st_mode))
    actual = {p.relative_to(target).as_posix() for p in target.rglob("*") if p.is_file()}
    failed = False
    for name, (raw, mode) in expected.items():
        path = target / name
        if args.check:
            if not path.is_file() or path.read_bytes() != raw or stat.S_IMODE(path.stat().st_mode) != mode:
                print(f"Codex Orbit package differs: {name}; run python3 scripts/sync-orbit-packages.py", file=sys.stderr)
                failed = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
            path.chmod(mode)
    for name in sorted(actual - expected.keys()):
        if args.check:
            print(f"stale generated Codex Orbit file: {name}", file=sys.stderr)
            failed = True
        else:
            (target / name).unlink()
    return int(failed)


if __name__ == "__main__":
    sys.exit(main())
